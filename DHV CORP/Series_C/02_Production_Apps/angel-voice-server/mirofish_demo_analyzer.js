/**
 * Mirofish Automated Inbound Demo Call Performance Analytics Pipeline
 * ====================================================================
 * Evaluates every completed demo call for sales performance, intake accuracy,
 * active empathy, consultative ROI pitch, and executive conversion.
 *
 * Operationalizes the CEO directive:
 *   "EVERY DEMO CALL MUST BE USED TO IMPROVE THE BOT'S SALES PERFORMANCE"
 */

const fs = require('fs');
const path = require('path');
let secondListenerRag = null;
try { secondListenerRag = require('./second_listener_rag_engine'); } catch (_) {
  try { secondListenerRag = require('../02_Production_Apps/second_listener_rag_engine'); } catch (_2) {}
}

const TRADE_SPECIALISTS = new Set(['plumbing', 'hvac', 'roofing', 'electrical', 'dental', 'legal_pi', 'general_contractor', 'after_hours_crisis']);

/**
 * Analyze a completed call record using Mirofish auditing rules.
 * @param {object} callRecord - The call record object generated by post_call_dashboard.js
 * @returns {object} Mirofish Audit Report
 */
function analyzeDemoCall(callRecord) {
  if (!callRecord) return null;

  const transcript = callRecord.transcript || '';
  const fnol = callRecord.fnol || callRecord.fnolData || {};
  const ticket = callRecord.ticket || {};
  const lowerTranscript = transcript.toLowerCase();

  const detectedSpec = String(callRecord.specialist || callRecord.vertical || ticket.specialist || '').toLowerCase();
  const isTradeSpecialist = Boolean(
    TRADE_SPECIALISTS.has(detectedSpec) ||
    lowerTranscript.includes('plumbing specialist') ||
    lowerTranscript.includes('especialista de plomería') ||
    lowerTranscript.includes('hvac specialist') ||
    lowerTranscript.includes('roofing specialist') ||
    lowerTranscript.includes('electrical specialist') ||
    lowerTranscript.includes('dental specialist') ||
    lowerTranscript.includes('legal intake specialist') ||
    lowerTranscript.includes('crisis response specialist')
  );
  const activeSpecialist = isTradeSpecialist ? (TRADE_SPECIALISTS.has(detectedSpec) ? detectedSpec : 'plumbing') : 'claims';

  // 1. Category 1: Intake Accuracy & Core Competency (0-100)
  let intakePoints = 0;
  let capturedCount = 0;
  let targetSlots = [];

  // Pass 4: Adversarial Persona & Multi-Turn Stress helpers.
  // Mid-sentence digit corrections ("5-5-5, wait no, it's 5-5-6") should resolve to the
  // last-stated value rather than being rejected as a garbled slot.
  function resolveMidSentenceCorrection(raw) {
    if (typeof raw !== 'string') return raw;
    const correctionSplit = raw.split(/\b(?:wait no|no wait|sorry|actually|correction|make that|i mean|digo|perdón|me equivoqué|mejor dicho)\b[,:\s-]*/i);
    return correctionSplit.length > 1 ? correctionSplit[correctionSplit.length - 1].trim() : raw;
  }

  function isSlotSemanticallyValid(slot, val) {
    if (!val || typeof val !== 'string') return false;
    const clean = resolveMidSentenceCorrection(val).trim();
    if (clean.length < 2 || clean === 'Not captured on this call' || clean === 'Not Provided' || clean === 'Pending Verification') return false;
    // Reject noisy-roadside-audio ASR artifacts (overlapping traffic/wind noise, dropped frames)
    if (/\[(?:inaudible|unintelligible|noise|static|crosstalk|garbled|wind|traffic noise|engine noise|overlapping|interrupt(?:ed|ion)?)\]/i.test(clean)) return false;
    // Reject truncated leading words ("terday", "ktober", "morrow")
    if (/^(?:terday|ktober|chuan|morrow|ternoon|ening)\b/i.test(clean)) return false;
    // Reject interrupted-speech fragments that were cut off mid-word/mid-sentence
    // (caller talked over or was talked over before finishing the slot value)
    if (/(?:--|—)\s*$/.test(clean) || /\bcut\s+off\b/i.test(clean)) return false;
    // Reject questions in data slots
    if (clean.endsWith('?') || /^(what|how|why|can|could|when|is|are|do|does|tell me)\b/i.test(clean)) return false;
    // Reject currency / pricing artifacts in slots
    if (/^\$\d+(\.\d{2})?$/.test(clean) || (slot !== 'problemDescription' && /\b(cost|price|quote|estimate)\b/i.test(clean))) return false;
    // Reject meta complaints
    if (/\b(why are you asking|stop repeating|no logic|broken|confused)\b/i.test(clean)) return false;
    if (slot === 'urgency') {
      if (clean.length > 55 || /\bshut-?off\s+valve\b/i.test(clean)) return false;
    }
    if (slot === 'vehicle' || slot === 'vehicleInfo') {
      if (secondListenerRag && typeof secondListenerRag.scoreVehicleSpecificity === 'function') {
        if (secondListenerRag.scoreVehicleSpecificity(clean) < 2) return false;
      }
    }
    if (slot === 'serviceAddress' || slot === 'location' || slot === 'locationOfLoss') {
      // Must not contain unnormalized ASR colon street numbers or trailing damage/narrative clauses
      if (/\b\d{1,2}:\d{2}\s+[A-Za-z]+\s+(?:Drive|Dr|Street|St|Ave|Avenue|Road|Rd|Lane|Ln|Blvd)\b/i.test(clean)) return false;
      if (/\b(?!(?:Spring|Irving|Crossing|Landing|Parking|Shopping|Sterling)\b)[a-z]{4,}ing\s+(?:the|my|a|an|up|down|off|out|into|quarter|golf|heavy|water|glass|hood|roof|windshield|bumper|fence)\b/i.test(clean)) return false;
      if (/\b(?:and\s+(?:left|leaving|cracked|broke|smashed|ripped|knocked|caused|flooded)|while\s+(?:i|we|it)\s+(?:was|were)|with\s+quarter-size)\b/i.test(clean)) return false;
      if (secondListenerRag && typeof secondListenerRag.isStructurallyGarbledStreet === 'function') {
        const numMatch = clean.match(/^\d+\s+([A-Za-z0-9\s]{2,40}?)(?:,|\bin\b|$)/);
        if (numMatch && secondListenerRag.isStructurallyGarbledStreet(numMatch[1])) return false;
      }
      // Must not be a bare city or generic landmark without street
      if (/^(?:in\s+|at\s+)?(Dallas|Fort Worth|Tyler|Austin|Houston|San Antonio|El Paso|Plano|Frisco|Denton|Arlington|Wichita Falls|Conway|Broken Bow|Longview|Lubbock|Midland|Odessa|Amarillo|Waco)(?:,?\s*(?:TX|Texas))?[.!?]?$/i.test(clean)) return false;
      if (/^walmart\s+(?:in\s+)?(?:dallas|houston|austin)[.!?]?$/i.test(clean)) return false;
    }
    return true;
  }

  // Fatal crash detector
  if (lowerTranscript.includes("application error has occurred") || lowerTranscript.includes("an application error")) {
    intakePoints = 0;
  } else if (isTradeSpecialist) {
    targetSlots = ['callerName', 'serviceAddress', 'problemDescription', 'urgency', 'preferredWindow'];
    targetSlots.forEach(slot => {
      const val = ticket[slot] || fnol[slot] || (slot === 'callerName' ? callRecord.callerName : null);
      if (isSlotSemanticallyValid(slot, val)) {
        capturedCount++;
      }
    });

    intakePoints = Math.round((capturedCount / targetSlots.length) * 85);

    // Emergency containment guidance verification
    const emergencyReported = ticket.emergency ||
      /burst|leak|flooding?|overflow|tuber[ií]a rota|inundaci[oó]n|fuga|sparking|smoke|breaker|gas|chest pain|bleeding|swelling|tarp/i.test(lowerTranscript);
    const containmentGiven = /shut-off valve|turn off your main water|cierre la llave de paso|breaker|disconnect|shut off|safe area|emergency|priority/i.test(lowerTranscript);

    if (emergencyReported && containmentGiven) {
      intakePoints += 15; // Rewarded life-safety containment triage
    } else if (!emergencyReported) {
      intakePoints += 15; // Non-emergency routine call intact
    }
  } else {
    // Claims / FNOL Demo: Core Competencies (FOL, Vehicle, Trip Dynamics/Road, Traffic Signals, Location)
    const lf = fnol.lossFacts || {};
    if (isSlotSemanticallyValid('lossDescription', fnol.lossDescription || fnol.narrative || lf.factsSummary)) intakePoints += 20;
    if (isSlotSemanticallyValid('vehicle', fnol.vehicleInfo)) intakePoints += 20;
    const callerOnlyLower = String(transcript || '')
      .split(/\r?\n/)
      .filter(l => !/^\s*(?:Demo Host|AI Agent Angel|Agent Angel|Executive Narrator|System):/i.test(l))
      .map(l => l.replace(/^\s*Caller:\s*/i, '').trim())
      .join(' ')
      .toLowerCase();
    const isNonCollision = ['glass', 'comprehensive', 'flood', 'hail', 'animal', 'theft', 'vandalism', 'fallingobject', 'towing_roadside'].includes(String(fnol.lossType || '').toLowerCase()) ||
      /breakdown|mechanical|towing_roadside|hail|hailstorm|granizo|aver[ií]a|theft|fire|vandal\w*|keyed|key\s+scratches|stolen|break-?in|incendio|robo|flood\w*|submerg\w*|rising\s+water|deer|animal|falling\s+object|tree\s+(?:branch|limb)|rock\s+chip|gravel|windshield|glass\s+(?:loss|claim|only)|\bparked\b/i.test(callerOnlyLower);
    if (lf.tripPurpose || lf.tripDynamics || lf.roadCondition || lf.impactPoint || lf.speed || fnol.folInvestigated || isNonCollision) intakePoints += 20;
    if (lf.trafficSignal || fnol.trafficControlsCaptured || lf.accidentTemplate || isNonCollision) intakePoints += 20;
    if (isSlotSemanticallyValid('location', fnol.locationOfLoss || fnol.location)) intakePoints += 20;
  }

  // Caller objection check: Penalize unhandled rejection of summary
  const callerRejectedSummary = /no logic|that's wrong|that is wrong|not right|doesn't make sense|incorrect/i.test(lowerTranscript);
  const botRepaired = /what detail|what was incorrect|what did i get wrong|which detail should i update|i've updated the|he actualizado|qué detalle debo actualizar|disculpe por/i.test(lowerTranscript);
  if (callerRejectedSummary && !botRepaired) {
    intakePoints = Math.max(0, intakePoints - 40);
  }
  intakePoints = Math.min(100, Math.max(0, intakePoints));

  // Pass 4: SMB price-objection stress ("too expensive", "no budget", "what's this going to cost us")
  const smbPriceObjectionRaised = /(too expensive|can't afford|cannot afford|no budget|not in (?:our|the) budget|what('?s| is) this (?:going to )?cost|that'?s a lot of money|we'?re a small (?:shop|business|company)|too pricey|sounds expensive|no es barato|demasiado caro|no tenemos presupuesto|cuánto (?:nos )?va a costar)/i.test(lowerTranscript);
  const smbPriceObjectionHandled = /(roi|return on investment|pays for itself|no (?:upfront|up-front) cost|zero-cost (?:carrier )?pilot|cost of a missed call|missed calls? cost you|flexible pricing|pricing scales with|free pilot|sin costo|se paga solo|retorno de (?:la )?inversión)/i.test(lowerTranscript);

  // 2. Category 2: Active Empathy, Reassurance & Jargon Control (0-100)
  let empathyPoints = 20; // Base floor

  const reflectsFacts = /\b(got it|understood|noted|documented at|thank you|gracias|marked as|flagged|priority dispatch|let me confirm|permítame confirmar|comprendido|anotado|entendido)\b/i.test(lowerTranscript);
  if (reflectsFacts) empathyPoints += 25;

  const hasEmpathyMarker =
    /\b(i'm so sorry|i am so sorry|lamento mucho|lo siento mucho|understand completely|comprendo perfectamente|here to help|estamos aquí para ayudarle|safety comes first|hope you're okay|espero que se encuentre bien|relieved no one is injured|me da alivio saber que no hay lesionados|help you get your claim started|ayudarle a iniciar su reclamo)\b/i.test(lowerTranscript);
  if (hasEmpathyMarker) empathyPoints += 20;

  const hasWarmPacing =
    /\b(take your time|whenever you're ready|no problem at all|right away|de inmediato|por su seguridad|for your safety|for your comfort|tómese su tiempo|no se preocupe|let me confirm the details|permítame confirmar los detalles)\b/i.test(lowerTranscript);
  if (hasWarmPacing) empathyPoints += 20;

  const hasPhotoDispatchAck = lowerTranscript.includes("siu upload link") || lowerTranscript.includes("text you a secure link") || lowerTranscript.includes("enlace de carga") || lowerTranscript.includes("enlace seguro") || lowerTranscript.includes("enlace de fotos") || lowerTranscript.includes("upload link") || lowerTranscript.includes("live dashboard link") || lowerTranscript.includes("panel en vivo") || lowerTranscript.includes("short live demo link") || lowerTranscript.includes("claim call summary report") || lowerTranscript.includes("informe de resumen de llamada") || lowerTranscript.includes("ai agent angel dot com slash u-a-t");
  if (hasPhotoDispatchAck) empathyPoints += 15;

  // Severe jargon penalties
  if (
    lowerTranscript.includes("third-party claim set up") ||
    lowerTranscript.includes("third-party claim set-up") ||
    lowerTranscript.includes("get this third-party claim")
  ) {
    empathyPoints -= 25;
  }
  if (lowerTranscript.includes("sub-second neural latency") || lowerTranscript.includes("carrier intake triage")) {
    empathyPoints -= 20;
  }

  // DR-02 check: Fabricating "relieved no one is injured" when caller never said no injuries
  const statedSafe = /(no injur|nobody hurt|no one hurt|nobody was hurt|no one was hurt|everyone is fine|everyone is ok|everyone is safe|fine, no hurt|sin lesiones|sin heridos|no hay heridos|todos estamos bien|nadie result)/i.test(lowerTranscript);
  const botAckedSafe = lowerTranscript.includes("relieved no one is injured") || lowerTranscript.includes("me da alivio saber que no hay lesionados");
  if (botAckedSafe && !statedSafe) {
    empathyPoints -= 35;
  }

  empathyPoints = Math.min(100, Math.max(0, empathyPoints));

  // 3. Category 3: Consultative Competency & Value Proposition (0-100)
  let consultativePoints = 0;

  // A. Proving Competency Through Live Intake (+30)
  if (intakePoints >= 70) consultativePoints += 30;
  else consultativePoints += Math.round((intakePoints / 70) * 30);

  // B. Demonstrating Operational Business Value (+30)
  if (isTradeSpecialist) {
    const addressesTradeValue =
      lowerTranscript.includes("after-hours") ||
      lowerTranscript.includes("first ring") ||
      lowerTranscript.includes("voicemail") ||
      lowerTranscript.includes("shut-off guidance") ||
      lowerTranscript.includes("priority dispatch") ||
      lowerTranscript.includes("emergency") ||
      lowerTranscript.includes("fuera de horario") ||
      lowerTranscript.includes("primer timbre") ||
      lowerTranscript.includes("buzón de voz");
    if (addressesTradeValue) consultativePoints += 30;
  } else {
    const addressesClaimsValue =
      lowerTranscript.includes("surge") ||
      lowerTranscript.includes("catastrophe") ||
      lowerTranscript.includes("speedai") ||
      lowerTranscript.includes("nuance dax") ||
      lowerTranscript.includes("audit 100 percent") ||
      lowerTranscript.includes("audit 100%") ||
      lowerTranscript.includes("108 customizable factors") ||
      lowerTranscript.includes("108 factors") ||
      lowerTranscript.includes("108 factores") ||
      lowerTranscript.includes("2% and 6%") ||
      lowerTranscript.includes("2 percent and 6 percent") ||
      lowerTranscript.includes("dos y el seis por ciento") ||
      lowerTranscript.includes("audit add-on") ||
      lowerTranscript.includes("complemento de auditoría") ||
      lowerTranscript.includes("50% or more") ||
      lowerTranscript.includes("50 percent or more") ||
      lowerTranscript.includes("loss adjustment expense") ||
      lowerTranscript.includes("lae") ||
      lowerTranscript.includes("axirate") ||
      lowerTranscript.includes("exif metadata") ||
      lowerTranscript.includes("forensic chain of custody") ||
      lowerTranscript.includes("cadena de custodia forense") ||
      lowerTranscript.includes("towing validation") ||
      lowerTranscript.includes("módulo automatizado de remolque") ||
      lowerTranscript.includes("facturas de grúas") ||
      lowerTranscript.includes("documentation loop");
    if (addressesClaimsValue) consultativePoints += 30;
  }

  // C. Digital Link / Preview Dispatch (+20)
  const isHomeownerIntake = String(callRecord.callerRole || '').toUpperCase() === 'HOMEOWNER' || (ticket && ticket.mode === 'intake');
  const offersDashboardOrSchedule =
    lowerTranscript.includes("live dashboard") ||
    lowerTranscript.includes("dashboard link") ||
    lowerTranscript.includes("private link") ||
    lowerTranscript.includes("panel en vivo") ||
    lowerTranscript.includes("enlace privado") ||
    lowerTranscript.includes("pilot scheduling link") ||
    lowerTranscript.includes("calendar booking link") ||
    lowerTranscript.includes("enlace de calendario") ||
    lowerTranscript.includes("claim call summary report") ||
    lowerTranscript.includes("axirate dashboard") ||
    lowerTranscript.includes("informe de resumen de llamada") ||
    lowerTranscript.includes("panel axirate") ||
    lowerTranscript.includes("short live demo link") ||
    (isHomeownerIntake && (
      lowerTranscript.includes("secure link") ||
      lowerTranscript.includes("photo upload link") ||
      lowerTranscript.includes("enlace seguro") ||
      lowerTranscript.includes("subir fotos")
    ));
  if (offersDashboardOrSchedule) consultativePoints += 20;

  const hasCategoryWedge = lowerTranscript.includes("speedai") || lowerTranscript.includes("nuance dax") || lowerTranscript.includes("audit 100 percent") || lowerTranscript.includes("auditar en tiempo real el 100") || lowerTranscript.includes("auditar el 100%") || lowerTranscript.includes("axirate") || lowerTranscript.includes("108 customizable factors") || lowerTranscript.includes("108 factors") || lowerTranscript.includes("108 factores") || lowerTranscript.includes("audit add-on") || lowerTranscript.includes("warm transfer") || lowerTranscript.includes("acord 125") || lowerTranscript.includes("registro acord") || lowerTranscript.includes("siu forensic") || lowerTranscript.includes("30-day zero-cost carrier pilot") || lowerTranscript.includes("piloto de treinta días sin costo") || (isTradeSpecialist && (lowerTranscript.includes("traditional answering service") || lowerTranscript.includes("competitor's voicemail") || lowerTranscript.includes("competitor voicemails") || lowerTranscript.includes("servicetitan") || lowerTranscript.includes("housecall") || lowerTranscript.includes("jobber") || lowerTranscript.includes("servicio de contestaci") || lowerTranscript.includes("buzón") || (isHomeownerIntake && (lowerTranscript.includes("bring the right tools") || lowerTranscript.includes("confirm your appointment") || lowerTranscript.includes("revisar el problema con anticipación") || lowerTranscript.includes("confirmará su horario")))));
  if (hasCategoryWedge) consultativePoints += 20;

  // Penalize unresolved SMB price objections; a surfaced-and-rebutted objection is a selling point.
  if (smbPriceObjectionRaised && !smbPriceObjectionHandled) {
    consultativePoints = Math.max(0, consultativePoints - 25);
  } else if (smbPriceObjectionRaised && smbPriceObjectionHandled) {
    consultativePoints = Math.min(100, consultativePoints + 10);
  }
  consultativePoints = Math.min(100, Math.max(0, consultativePoints));

  // 4. Category 4: Flow, Pacing & Anti-Stacking Gate (0-100)
  let flowPoints = 85;
  const botOnlyLines = transcript.split(/\r?\n/).filter(l => /^(?:BOT|AI Agent Angel|Demo Host|Agent Angel)/i.test(l.trim())).join('\n').toLowerCase();
  const isQuestionStacking = /and did any airbags deploy or are fluids leaking/i.test(botOnlyLines) || /\b(did any airbags deploy.*are fluids leaking)\b/i.test(botOnlyLines);
  if (isQuestionStacking) flowPoints -= 40;

  const hasCallerComplaint = /too many errors|stop repeating|why do you keep repeating|already told you|repetitive|not listening|where is your logic|stopped listening|garbage|\bfail(ed|ure)?\s+(bot|system|ai|intake|call)\b/i.test(lowerTranscript);
  if (hasCallerComplaint) flowPoints -= 60;

  // Bonus for Overhaul Compliance: 3-Part Framing + 2%-6% Audit Discovery + Audit Add-On Walkthrough (+15 up to 100)
  if (
    (lowerTranscript.includes("three-part") || lowerTranscript.includes("tres partes") || lowerTranscript.includes("claim call summary report") || lowerTranscript.includes("informe de resumen de llamada")) &&
    (lowerTranscript.includes("2% and 6%") || lowerTranscript.includes("2 percent and 6 percent") || lowerTranscript.includes("dos y el seis por ciento") || lowerTranscript.includes("what percentage of your fnol") || lowerTranscript.includes("qué porcentaje de sus llamadas"))
  ) {
    flowPoints = Math.min(100, flowPoints + 15);
  }

  if (lowerTranscript.includes("start over") || lowerTranscript.includes("reiniciar")) {
    if (
      lowerTranscript.includes("very beginning, or just correct") ||
      lowerTranscript.includes("principio o solo corregir")
    ) {
      flowPoints += 15;
    } else {
      flowPoints -= 20;
    }
  }
  flowPoints = Math.min(100, Math.max(0, flowPoints));

  // 5. Category 5: Value-Driven Conversion (0-100)
  let conversionPoints = 40;
  if (offersDashboardOrSchedule) conversionPoints += 30;
  if (
    lowerTranscript.includes("claim reference") ||
    lowerTranscript.includes("recorded under reference") ||
    lowerTranscript.includes("registrado con la referencia") ||
    lowerTranscript.includes("service request") ||
    lowerTranscript.includes("job-ticket") ||
    lowerTranscript.includes("ticket reference") ||
    lowerTranscript.includes("solicitud de servicio") ||
    lowerTranscript.includes("dispatched to your mobile phone") ||
    lowerTranscript.includes("to your mobile number") ||
    lowerTranscript.includes("a su teléfono móvil") ||
    lowerTranscript.includes("enviado a su teléfono") ||
    lowerTranscript.includes("calendar booking link") ||
    lowerTranscript.includes("enlace directo de calendario") ||
    lowerTranscript.includes("15-minute walkthrough") ||
    lowerTranscript.includes("sesión de quince minutos")
  ) {
    conversionPoints += 30;
  }
  conversionPoints = Math.min(100, Math.max(0, conversionPoints));

  // Overall Mirofish Score Calculation (Weighted)
  let overallMirofishScore = Math.round(
    (intakePoints * 0.25) +
    (empathyPoints * 0.20) +
    (consultativePoints * 0.25) +
    (flowPoints * 0.15) +
    (conversionPoints * 0.15)
  );

  if (hasCallerComplaint) {
    overallMirofishScore = Math.min(overallMirofishScore, 35);
  }
  if (isQuestionStacking) {
    overallMirofishScore = Math.min(overallMirofishScore, 58);
  }

  let ratingBand = 'NEEDS_OPTIMIZATION';
  if (overallMirofishScore >= 85 && !hasCallerComplaint && !isQuestionStacking) ratingBand = 'EXCELLENT';
  else if (overallMirofishScore >= 70 && !hasCallerComplaint && !isQuestionStacking) ratingBand = 'STRONG';

  // Extract What Went Well & Needs Improvement
  const whatWentWell = [];
  const needsImprovement = [];
  const recommendedBotFixes = [];

  if (intakePoints >= 80) {
    whatWentWell.push(isTradeSpecialist ? 'High slot capture accuracy across trade intake fields with safety triage.' : 'High slot capture accuracy across core FNOL fields.');
  } else {
    needsImprovement.push(`Incomplete slot capture (${capturedCount}/${targetSlots.length} fields populated).`);
  }

  if (empathyPoints >= 85) {
    whatWentWell.push('Clear, empathetic acknowledgment without insurance or technical jargon.');
  } else {
    needsImprovement.push('Empathy phrasing contained jargon or lacked reassuring tone.');
    recommendedBotFixes.push('Ensure empathetic acknowledgment and containment guidance precede administrative prompts.');
  }

  if (consultativePoints >= 75) {
    whatWentWell.push(isTradeSpecialist ? 'Proved competency via 24/7 after-hours triage and non-pushy schedule link.' : 'Consultative posture demonstrated LAE reduction, surge capacity, and Guidewire readiness.');
  } else {
    needsImprovement.push('Consultative score impacted by buzzword rambling, hard-close pressure, or missing business value.');
    recommendedBotFixes.push('Focus on proving competency through live intake and consultative operational value rather than pushing sales.');
  }
  if (smbPriceObjectionRaised && !smbPriceObjectionHandled) {
    needsImprovement.push('SMB price objection was raised but never rebutted with ROI or zero-cost-pilot framing.');
    recommendedBotFixes.push('When caller objects to cost, pivot to ROI/missed-call-cost framing or the zero-cost pilot offer.');
  }

  if (conversionPoints >= 75) {
    whatWentWell.push('Dispatched live dashboard/dispatch preview link with zero-pressure close.');
  } else {
    needsImprovement.push('Failed to dispatch live preview/dashboard link.');
    recommendedBotFixes.push('Ensure closing wrap offers live dashboard or dispatch schedule link via SMS.');
  }

  const analysisReport = {
    callSid: callRecord.callSid,
    claimRef: callRecord.claimRef || ticket.claimRef || 'REF-DEMO',
    specialist: activeSpecialist,
    vertical: activeSpecialist,
    timestamp: new Date().toISOString(),
    callerRole: callRecord.callerRole || ticket.salesRole || 'UNKNOWN',
    language: callRecord.language || 'en',
    overallMirofishScore,
    ratingBand,
    categoryScores: {
      intakeAccuracy: intakePoints,
      empathyAndTone: empathyPoints,
      consultativePitch: consultativePoints,
      objectionHandling: flowPoints,
      leadCaptureAndConversion: conversionPoints
    },
    whatWentWell,
    needsImprovement,
    recommendedBotFixes
  };

  // Persist Mirofish Analysis Report locally (unless skipPersist is set for batch benchmarks)
  if (!callRecord.skipPersist) {
    try {
      const outputDir = path.join(__dirname, 'call_records', 'mirofish');
      fs.mkdirSync(outputDir, { recursive: true });

      const reportFile = path.join(outputDir, `${callRecord.callSid}_mirofish_analysis.json`);
      fs.writeFileSync(reportFile, JSON.stringify(analysisReport, null, 2), 'utf8');

      // Update Master Audit Ledger
      const ledgerFile = path.join(outputDir, 'inbound_demo_calls_audit_ledger.json');
      let ledger = [];
      if (fs.existsSync(ledgerFile)) {
        try {
          ledger = JSON.parse(fs.readFileSync(ledgerFile, 'utf8'));
        } catch (e) {
          ledger = [];
        }
      }
      // Prepend latest report
      ledger = [analysisReport, ...ledger.filter(item => item.callSid !== callRecord.callSid)];
      fs.writeFileSync(ledgerFile, JSON.stringify(ledger, null, 2), 'utf8');
    } catch (e) {
      console.error('[MIROFISH ANALYSIS ERROR]', e.message);
    }
  }

  return analysisReport;
}

