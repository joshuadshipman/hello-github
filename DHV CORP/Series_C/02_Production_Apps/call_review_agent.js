const REVIEW_STATES = Object.freeze({
  PENDING: 'pending',
  IN_REVIEW: 'in_review',
  REVIEW_COMPLETE: 'review_complete',
  DEFECTS_DETECTED: 'defects_detected',
  FLYWHEEL_TRIGGERED: 'flywheel_triggered',
  APPEAL_REQUESTED: 'appeal_requested',
  APPEAL_RESOLVED: 'appeal_resolved',
  CLOSED: 'closed'
});

const VALID_STATE_TRANSITIONS = Object.freeze({
  [REVIEW_STATES.PENDING]: Object.freeze([REVIEW_STATES.IN_REVIEW, REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.IN_REVIEW]: Object.freeze([REVIEW_STATES.REVIEW_COMPLETE, REVIEW_STATES.DEFECTS_DETECTED, REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.REVIEW_COMPLETE]: Object.freeze([REVIEW_STATES.APPEAL_REQUESTED, REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.DEFECTS_DETECTED]: Object.freeze([REVIEW_STATES.FLYWHEEL_TRIGGERED, REVIEW_STATES.APPEAL_REQUESTED, REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.FLYWHEEL_TRIGGERED]: Object.freeze([REVIEW_STATES.APPEAL_REQUESTED, REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.APPEAL_REQUESTED]: Object.freeze([REVIEW_STATES.APPEAL_RESOLVED, REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.APPEAL_RESOLVED]: Object.freeze([REVIEW_STATES.CLOSED]),
  [REVIEW_STATES.CLOSED]: Object.freeze([])
});

const FLYWHEEL_DEFECT_THRESHOLD = 12;

/**
 * Validates incoming webhook payload contracts across Stripe, Twilio, and call review triggers.
 * Rejects malformed or foreign payloads before state mutations occur.
 */
function isValidWebhookPayload(event) {
  if (!event || typeof event !== 'object' || Array.isArray(event)) {
    return false;
  }

  // Type 1: Standard event structure { id: string, type: string, data: { object: { ... } } }
  if (
    typeof event.id === 'string' &&
    event.id.length > 0 &&
    typeof event.type === 'string' &&
    event.type.length > 0 &&
    event.data &&
    typeof event.data === 'object' &&
    event.data.object &&
    typeof event.data.object === 'object' &&
    !Array.isArray(event.data.object) &&
    ((typeof event.data.object.id === 'string' && event.data.object.id.length > 0) ||
      (typeof event.data.object.callSid === 'string' && event.data.object.callSid.length > 0))
  ) {
    return true;
  }

  // Type 2: Direct Twilio/telephony status callback { CallSid: string, CallStatus: string }
  if (
    ((typeof event.CallSid === 'string' && event.CallSid.length > 0) ||
      (typeof event.callSid === 'string' && event.callSid.length > 0)) &&
    ((typeof event.CallStatus === 'string' && event.CallStatus.length > 0) ||
      (typeof event.callStatus === 'string' && event.callStatus.length > 0) ||
      (typeof event.status === 'string' && event.status.length > 0))
  ) {
    return true;
  }

  // Type 3: Direct call review post-call webhook payload { transcriptPath: string, acordPath: string }
  if (
    typeof event.transcriptPath === 'string' &&
    event.transcriptPath.length > 0 &&
    ((typeof event.acordPath === 'string' && event.acordPath.length > 0) ||
      (typeof event.ticketPath === 'string' && event.ticketPath.length > 0) ||
      (typeof event.callSid === 'string' && event.callSid.length > 0))
  ) {
    return true;
  }

  return false;
}

/**
 * Executes a governed state transition for a call review record.
 * Guarantees idempotency on duplicate events.
 */
function transitionReviewState(record, nextState, options) {
  options = options || {};
  if (!record || typeof record !== 'object') {
    return { ok: false, reason: 'invalid_record' };
  }

  const currentState = record.state || REVIEW_STATES.PENDING;
  if (!Object.values(REVIEW_STATES).includes(nextState)) {
    return { ok: false, reason: 'unknown_target_state', targetState: nextState };
  }

  if (currentState === nextState) {
    return { ok: true, duplicate: true, state: currentState, reason: 'already_in_state' };
  }

  const allowed = VALID_STATE_TRANSITIONS[currentState] || [];
  if (!allowed.includes(nextState) && !options.force) {
    return {
      ok: false,
      reason: 'invalid_transition',
      currentState,
      targetState: nextState,
      allowedTransitions: allowed
    };
  }

  const previousState = currentState;
  record.state = nextState;
  record.stateUpdatedAt = new Date().toISOString();

  return {
    ok: true,
    duplicate: false,
    previousState,
    state: nextState
  };
}

/**
 * Post-call Groq/AxiRate flywheel trigger.
 * Fires once per call when defectCount >= 12; idempotent, safe against non-numeric or negative counts.
 */
function triggerFlywheel(callId, defectCount, deps) {
  deps = deps || {};
  const fired = deps.fired || new Set();
  const flywheel = deps.flywheel || { trigger: function () {} };

  if (typeof callId !== 'string' || callId.length === 0) {
    return { ok: false, reason: 'invalid_call_id' };
  }
  if (!Number.isFinite(defectCount) || defectCount < 0) {
    return { ok: false, reason: 'invalid_defect_count' };
  }
  if (defectCount < FLYWHEEL_DEFECT_THRESHOLD) {
    return {
      ok: true,
      fired: false,
      reason: 'below_threshold',
      defectCount,
      threshold: FLYWHEEL_DEFECT_THRESHOLD
    };
  }
  if (fired.has(callId)) {
    return { ok: true, fired: false, reason: 'already_fired', callId };
  }

  try {
    flywheel.trigger({
      callId,
      defectCount,
      threshold: FLYWHEEL_DEFECT_THRESHOLD,
      triggeredAt: new Date().toISOString()
    });
    fired.add(callId);
    return { ok: true, fired: true, callId, defectCount };
  } catch (err) {
    return { ok: false, fired: false, reason: 'flywheel_threw', error: err && err.message };
  }
}

/**
 * verify_prospect_gate handoff.
 * Strict fail-closed: missing gate, throwing gate, or non-true return value blocks onboarding/review.
 */
function verifyProspectGateHandoff(prospect, deps) {
  deps = deps || {};
  const gate = deps.verifyProspectGate;

  if (typeof gate !== 'function') {
    return { ok: false, blocked: true, reason: 'gate_unavailable' };
  }

  let result;
  try {
    result = gate(prospect);
  } catch (err) {
    return { ok: false, blocked: true, reason: 'gate_threw', error: err && err.message };
  }

  if (!result || result.pass !== true) {
    return { ok: false, blocked: true, reason: (result && result.reason) || 'gate_denied' };
  }

  return { ok: true, blocked: false, prospect: result.prospect || prospect };
}

/**
 * Second Brain sync seam.
 * Best-effort: never throws into caller; reports explicit success/failure.
 */
function syncToSecondBrain(reviewRecord, deps) {
  deps = deps || {};
  const secondBrain = deps.secondBrain;

  if (!reviewRecord || typeof reviewRecord !== 'object') {
    return { ok: false, synced: false, reason: 'invalid_record' };
  }
  if (!secondBrain || typeof secondBrain.sync !== 'function') {
    return { ok: false, synced: false, reason: 'second_brain_unavailable' };
  }

  try {
    secondBrain.sync(reviewRecord);
    return { ok: true, synced: true, timestamp: new Date().toISOString() };
  } catch (err) {
    return { ok: false, synced: false, reason: 'sync_failed', error: err && err.message };
  }
}

/**
 * Deterministic Pass 3 Cross-System Handoff Seam Gate runner.
 */
function runCrossSystemHandoffSeamGate() {
  const results = {};

  // 1. Webhook payload contract validation
  results.rejectsNull = isValidWebhookPayload(null) === false;
  results.rejectsMalformed = isValidWebhookPayload({ id: 'evt_1' }) === false &&
    isValidWebhookPayload({ id: 'evt_1', type: 'checkout.session.completed', data: { object: {} } }) === false;
  results.acceptsStandardEvent = isValidWebhookPayload({
    id: 'evt_1', type: 'checkout.session.completed', data: { object: { id: 'cus_1' } }
  }) === true;
  results.acceptsTwilio = isValidWebhookPayload({
    CallSid: 'CA1234567890abcdef', CallStatus: 'completed'
  }) === true;
  results.acceptsReviewWebhook = isValidWebhookPayload({
    transcriptPath: 'transcripts/call_1.txt', acordPath: 'acord/call_1.json'
  }) === true;

  // 2. Cross-service state transitions
  const record = { id: 'call_test_1', state: REVIEW_STATES.PENDING };
  const step1 = transitionReviewState(record, REVIEW_STATES.IN_REVIEW);
  const step2 = transitionReviewState(record, REVIEW_STATES.DEFECTS_DETECTED);
  const step3 = transitionReviewState(record, REVIEW_STATES.FLYWHEEL_TRIGGERED);
  const retry = transitionReviewState(record, REVIEW_STATES.FLYWHEEL_TRIGGERED);
  const invalid = transitionReviewState({ state: REVIEW_STATES.CLOSED }, REVIEW_STATES.IN_REVIEW);

  results.stateTransitions = step1.ok && step2.ok && step3.ok;
  results.idempotentRetry = retry.ok && retry.duplicate === true;
  results.blocksInvalidTransition = invalid.ok === false;

  // 3. Post-call 12-defect Groq/AxiRate flywheel trigger
  const fired = new Set();
  const triggerCalls = [];
  const flywheelDeps = { fired, flywheel: { trigger: (p) => triggerCalls.push(p) } };
  const belowThreshold = triggerFlywheel('call_1', FLYWHEEL_DEFECT_THRESHOLD - 1, flywheelDeps);
  const atThreshold = triggerFlywheel('call_1', FLYWHEEL_DEFECT_THRESHOLD, flywheelDeps);
  const refireAttempt = triggerFlywheel('call_1', FLYWHEEL_DEFECT_THRESHOLD, flywheelDeps);
  const invalidCount = triggerFlywheel('call_2', -5, flywheelDeps);
  const invalidId = triggerFlywheel('', 15, flywheelDeps);

  results.flywheelThresholdIs12 = FLYWHEEL_DEFECT_THRESHOLD === 12;
  results.flywheelGatesOnThreshold = belowThreshold.fired === false && atThreshold.fired === true;
  results.flywheelFiresOnce = refireAttempt.fired === false && triggerCalls.length === 1;
  results.flywheelRejectsInvalid = invalidCount.ok === false && invalidId.ok === false;

  // 4. verify_prospect_gate handoff (fail-closed)
  const missingGate = verifyProspectGateHandoff({ id: 'p1' }, {});
  const throwingGate = verifyProspectGateHandoff({ id: 'p1' }, { verifyProspectGate: () => { throw new Error('boom'); } });
  const denyingGate = verifyProspectGateHandoff({ id: 'p1' }, { verifyProspectGate: () => ({ pass: false }) });
  const truthyNotStrictGate = verifyProspectGateHandoff({ id: 'p1' }, { verifyProspectGate: () => ({ pass: 1 }) });
  const passingGate = verifyProspectGateHandoff({ id: 'p1' }, { verifyProspectGate: () => ({ pass: true }) });

  results.gateFailClosed = missingGate.blocked === true && throwingGate.blocked === true &&
    denyingGate.blocked === true && truthyNotStrictGate.blocked === true;
  results.gateOpensOnExplicitPass = passingGate.ok === true && passingGate.blocked === false;

  // 5. Second Brain sync (best-effort, non-throwing)
  let threwIntoCaller = false;
  let outageResult;
  let okResult;
  try {
    outageResult = syncToSecondBrain({ callId: 'call_1' }, { secondBrain: null });
    syncToSecondBrain({ callId: 'call_1' }, { secondBrain: { sync: () => { throw new Error('down'); } } });
    okResult = syncToSecondBrain({ callId: 'call_1' }, { secondBrain: { sync: () => {} } });
  } catch (e) {
    threwIntoCaller = true;
  }
  results.secondBrainNeverThrows = threwIntoCaller === false;
  results.secondBrainReportsOutage = outageResult && outageResult.ok === false && outageResult.synced === false;
  results.secondBrainReportsSuccess = okResult && okResult.ok === true && okResult.synced === true;

  const passed = Object.values(results).every(Boolean);
  return {
    pass: passed,
    results,
    evidence: passed ? 'All Pass 3 seams verified' : 'Seam failure: ' + JSON.stringify(results)
  };
}

