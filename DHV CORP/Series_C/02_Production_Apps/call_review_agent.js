/**
 * Due Process Appeal Manager
 * Handles submission, adjudication, and tracking of agent/representative appeals.
 */
class DueProcessAppealManager {
  constructor() {
    this.appeals = new Map();
  }

  /**
   * Registers a human re-review appeal for a call review report.
   * @param {Object} reviewReport - The evaluated review report
   * @param {Object} appealData - Appellant details, reason, contested metrics
   * @returns {Object} Updated review report with appeal recorded
   */
  requestAppeal(reviewReport, appealData = {}) {
    if (!reviewReport || typeof reviewReport !== 'object') {
      throw new Error('Valid review report object required for appeal registration.');
    }
    if (!appealData.appellantId) {
      throw new Error('Appeal requires a valid appellantId (representative, supervisor, or agent).');
    }
    if (!appealData.reason || typeof appealData.reason !== 'string' || appealData.reason.trim().length < 5) {
      throw new Error('Appeal requires substantive reason text (minimum 5 characters).');
    }

    const appealId = `APL-${Date.now()}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
    const timestamp = new Date().toISOString();

    const appealRecord = {
      appealId,
      filedAt: timestamp,
      appellantId: String(appealData.appellantId).trim(),
      appellantType: appealData.appellantType || 'REPRESENTATIVE',
      reason: String(appealData.reason).trim(),
      contestedMetrics: Array.isArray(appealData.contestedMetrics) ? appealData.contestedMetrics : [],
      status: APPEAL_STATUS.REQUESTED,
      adjudication: null
    };

    reviewReport.appealStatus = APPEAL_STATUS.REQUESTED;
    reviewReport.flagForHumanReview = true;
    reviewReport.appealPending = true;
    reviewReport.humanReviewReason = `Due process appeal filed by ${appealRecord.appellantId}: ${appealRecord.reason}`;

    if (!Array.isArray(reviewReport.appealHistory)) {
      reviewReport.appealHistory = [];
    }
    reviewReport.appealHistory.push(appealRecord);
    this.appeals.set(appealId, { appealRecord, reviewId: reviewReport.reviewId });

    return reviewReport;
  }

  /**
   * Adjudicates an active appeal by an authorized human supervisor.
   * @param {Object} reviewReport - The review report to adjudicate
   * @param {Object} adjudication - Human reviewer decision and adjustments
   * @returns {Object} Updated review report with final human adjudication
   */
  adjudicateAppeal(reviewReport, adjudication = {}) {
    if (!reviewReport || typeof reviewReport !== 'object') {
      throw new Error('Valid review report object required for adjudication.');
    }
    if (!adjudication.reviewerId) {
      throw new Error('Adjudication requires a human supervisor reviewerId.');
    }

    const validDecisions = [APPEAL_STATUS.UPHELD, APPEAL_STATUS.OVERTURNED, APPEAL_STATUS.MODIFIED];
    if (!validDecisions.includes(adjudication.decision)) {
      throw new Error(`Invalid adjudication decision: ${adjudication.decision}. Must be UPHELD, OVERTURNED, or MODIFIED.`);
    }

    const activeAppeal = Array.isArray(reviewReport.appealHistory) && reviewReport.appealHistory.length > 0
      ? reviewReport.appealHistory[reviewReport.appealHistory.length - 1]
      : null;

    const timestamp = new Date().toISOString();
    const adjudicationRecord = {
      adjudicatedAt: timestamp,
      reviewerId: String(adjudication.reviewerId).trim(),
      decision: adjudication.decision,
      notes: String(adjudication.notes || 'Appeal reviewed and adjudicated by human supervisor.').trim(),
      adjustedScores: adjudication.adjustedScores || null
    };

    if (activeAppeal) {
      activeAppeal.status = adjudication.decision;
      activeAppeal.adjudication = adjudicationRecord;
    }

    reviewReport.appealStatus = adjudication.decision;
    reviewReport.appealPending = false;
    reviewReport.humanReviewed = true;
    reviewReport.humanReviewedBy = adjudicationRecord.reviewerId;
    reviewReport.humanReviewedAt = timestamp;

    // Apply adjustments if overturned or modified
    if (adjudication.decision === APPEAL_STATUS.OVERTURNED) {
      // Overturn all penalties on contested metrics
      const contested = activeAppeal ? activeAppeal.contestedMetrics : [];
      if (Array.isArray(reviewReport.metricResults)) {
        for (const m of reviewReport.metricResults) {
          if (contested.length === 0 || contested.includes(m.id)) {
            m.passed = true;
            m.score = 100;
            m.overturnedByHuman = true;
            m.humanNote = adjudicationRecord.notes;
          }
        }
      }
      // Clear critical violations if overturned
      if (Array.isArray(reviewReport.criticalViolations)) {
        reviewReport.criticalViolations = reviewReport.criticalViolations.map(v => ({
          ...v,
          overturnedByHuman: true,
          overturnedBy: adjudicationRecord.reviewerId
        }));
      }
      reviewReport.flagForHumanReview = false;
    } else if (adjudication.decision === APPEAL_STATUS.MODIFIED && adjudication.adjustedScores) {
      if (Array.isArray(reviewReport.metricResults)) {
        for (const m of reviewReport.metricResults) {
          if (typeof adjudication.adjustedScores[m.id] === 'number') {
            m.score = Math.max(0, Math.min(100, adjudication.adjustedScores[m.id]));
            m.passed = m.score >= 70;
            m.modifiedByHuman = true;
          }
        }
      }
    }

    // Recalculate composite scores
    recomputeReportScores(reviewReport);
    return reviewReport;
  }
}

/**
 * Animal Loss Intake Auditor
 * Implements neutral factual capture for animal collisions and enforces prohibitions
 * against stating coverage or veterinary claim availability.
 */
class AnimalLossIntakeAuditor {
  /**
   * Evaluates call text for animal collision loss details and compliance.
   * @param {string} fullTranscript - Full call transcript
   * @param {Array<Object>} turns - Parsed speaker turns
   * @returns {Object} Animal loss assessment report
   */
  auditAnimalLoss(fullTranscript, turns = []) {
    const text = String(fullTranscript || '');
    const isAnimalCollision = this.detectAnimalCollision(text);

    if (!isAnimalCollision) {
      return {
        isAnimalCollision: false,
        lossCategory: 'NON_ANIMAL_LOSS',
        factualCapture: null,
        complianceViolations: []
      };
    }

    // 1. Neutral 4-Point Factual Capture
    const speciesCapture = this.extractSpecies(text);
    const vehicleDamageCapture = this.extractVehicleDamage(text);
    const humanInjuryCapture = this.extractHumanInjury(text, turns);
    const safetyStatusCapture = this.extractSafetyStatus(text);

    // 2. Prohibited Coverage / Veterinary Statement Audit
    const complianceViolations = this.auditProhibitedStatements(turns);

    // 3. Evaluate Factual Capture Completeness
    const missingElements = [];
    if (!speciesCapture.identified) missingElements.push('animal_species');
    if (!vehicleDamageCapture.captured) missingElements.push('vehicle_damage');
    if (!humanInjuryCapture.injuryTriagePerformed) missingElements.push('human_injury_triage');
    if (!safetyStatusCapture.captured) missingElements.push('safety_status');

    // Warning if intake failed to triage human bodily injury (treating as property-damage only)
    const propertyDamageOnlyAssumptionError = !humanInjuryCapture.injuryTriagePerformed;

    return {
      isAnimalCollision: true,
      lossCategory: 'ANIMAL_COLLISION_FACTUAL_INTAKE',
      propertyDamageOnlyAssumptionError,
      prohibitedCoverageStatementsDetected: complianceViolations.length > 0,
      factualCapture: {
        animal_species: speciesCapture,
        vehicle_damage: vehicleDamageCapture,
        human_injury: humanInjuryCapture,
        safety_status: safetyStatusCapture
      },
      missingFactualElements: missingElements,
      factualCaptureScore: Math.round(((4 - missingElements.length) / 4) * 100),
      complianceViolations,
      neutralIntakeCertified: missingElements.length === 0 && complianceViolations.length === 0
    };
  }

  /**
   * Detects if the call pertains to an animal strike or collision.
   */
  detectAnimalCollision(text) {
    // Strip Angel's standard comprehensive peril menu question and insurance CAT (Catastrophe) surge terms so "CAT surge" does not false-trigger as a feline cat collision
    const cleaned = String(text || '')
      .replace(/such as hail,\s*flood water,\s*a falling tree branch,\s*windshield glass,\s*an animal strike,\s*vandalism,\s*or theft/gi, '')
      .replace(/\bcat\s+(?:surge|event|storm|team|claims?|adjuster|backlog|response|volume)\b/gi, '');

    const animalCollisionTriggers = [
      /\b(?:hit|struck|collided\s+with|ran\s+into)\s+(?:a\s+|an\s+)?(?:[a-zA-Z-]+\s+)?(?:deer|animal|dog|cow|cattle|horse|hog|boar|elk|critter|wildlife|bird)\b/i,
      /\b(?:deer|animal|wildlife|cattle|cow|hog|dog|elk)\s+(?:strike|impact|collision|hit|crossed|ran\s+out|bolted)\b/i,
      /\banimal\s+(?:collision|strike|impact|incident|accident)\b/i,
      /\bswerved\s+to\s+(?:avoid|miss)\s+(?:a\s+|an\s+)?(?:[a-zA-Z-]+\s+)?(?:deer|animal|dog)\b/i
    ];

    for (const pattern of animalCollisionTriggers) {
      if (pattern.test(cleaned)) return true;
    }

    // Fallback: check if any specific species from registry (excluding generic 'animal') is present alongside collision / strike keywords
    const hasCollisionContext = /\b(?:hit|struck|collision|accident|ran\s+out|bolted|impact|swerved|carcass|roadway)\b/i.test(cleaned);
    if (hasCollisionContext) {
      for (const species of ANIMAL_SPECIES_REGISTRY) {
        if (species.id === 'unspecified_animal') continue;
        for (const kw of species.keywords) {
          if (kw.test(cleaned)) return true;
        }
      }
    }

    return false;
  }

  /**
   * Extracts animal species factually.
   */
  extractSpecies(text) {
    const cleaned = String(text || '').replace(/\bcat\s+(?:surge|event|storm|team|claims?|adjuster|backlog|response|volume)\b/gi, '');
    for (const species of ANIMAL_SPECIES_REGISTRY) {
      for (const kw of species.keywords) {
        if (kw.test(cleaned)) {
          return {
            identified: true,
            speciesId: species.id,
            label: species.label,
            category: species.category,
            matchedText: cleaned.match(kw)[0]
          };
        }
      }
    }
    return {
      identified: false,
      speciesId: 'unknown_species',
      label: 'Unspecified Animal',
      category: 'unspecified',
      matchedText: null
    };
  }

  /**
   * Extracts vehicle damage points neutrally.
   */
  extractVehicleDamage(text) {
    const damagePoints = [];
    const damageChecks = [
      { part: 'front_bumper', regex: /(?:front\s+)?bumper/i },
      { part: 'grille_radiator', regex: /(?:grill|grille|radiator|coolant|steam)/i },
      { part: 'hood', regex: /hood/i },
      { part: 'windshield', regex: /(?:windshield|windscreen|glass)/i },
      { part: 'headlights', regex: /(?:headlight|head\s+lamp|light)/i },
      { part: 'fender_quarter_panel', regex: /(?:fender|quarter\s+panel|side)/i },
      { part: 'undercarriage', regex: /(?:undercarriage|oil\s+pan|underneath)/i },
      { part: 'airbag_deployment', regex: /airbag/i }
    ];

    for (const check of damageChecks) {
      if (check.regex.test(text)) {
        damagePoints.push(check.part);
      }
    }

    const drivableMatch = /(?:drivable|drove\s+home|can\s+drive|operating)/i.test(text);
    const inoperableMatch = /(?:not\s+drivable|inoperable|undrivable|towed|tow\s+truck)/i.test(text);

    return {
      captured: damagePoints.length > 0 || drivableMatch || inoperableMatch,
      damagePoints,
      drivability: inoperableMatch ? 'INOPERABLE' : (drivableMatch ? 'DRIVABLE' : 'UNCONFIRMED')
    };
  }

  /**
   * Extracts human bodily injury checks factually.
   * Prohibits treating animal collision as "property damage only" without inquiry.
   */
  extractHumanInjury(text, turns = []) {
    // Check if representative or caller inquired/disclosed injury
    const injuryInquiryPattern = /(?:anyone\s+(?:injured|hurt)|any\s+injuries|is\s+everyone\s+okay|paramedics|ambulance|ems|medical\s+attention)/i;

    const injuryReportedPattern = /(?:i(?:'m|\s+am)\s+hurt|neck\s+pain|back\s+pain|concussion|bleeding|passenger\s+(?:was\s+)?hurt|ambulance\s+came|went\s+to\s+the\s+er|hospital)/i;
    const noInjuryReportedPattern = /(?:nobody\s+(?:is|was)\s+(?:hurt|injured)|no\s+injuries|everyone(?:'s|\s+is)\s+(?:fine|safe|okay)|i'm\s+fine|we're\s+all\s+okay)/i;

    let injuryStatus = 'UNCONFIRMED';
    if (injuryReportedPattern.test(text)) {
      injuryStatus = 'INJURIES_REPORTED';
    } else if (noInjuryReportedPattern.test(text)) {
      injuryStatus = 'NO_INJURIES_CONFIRMED';
    }

    const injuryTriagePerformed = injuryInquiryPattern.test(text) || injuryStatus !== 'UNCONFIRMED';

    return {
      injuryTriagePerformed,
      injuryStatus,
      emsDispatched: /(?:ambulance|paramedic|ems|hospital|er)\b/i.test(text)
    };
  }

  /**
   * Extracts scene safety and vehicle mobility status.
   */
  extractSafetyStatus(text) {
    const safetyChecks = [
      { key: 'off_roadway', regex: /(?:shoulder|pulled\s+over|safe\s+location|parking\s+lot|off\s+the\s+road)/i },
      { key: 'hazard_on_road', regex: /(?:blocking\s+traffic|middle\s+of\s+the\s+road|lane\s+blocked|hazard)/i },
      { key: 'police_on_scene', regex: /(?:police|trooper|sheriff|officer|highway\s+patrol)/i },
      { key: 'towed', regex: /(?:towed|wrecker|flatbed|tow\s+truck)/i }
    ];

    const confirmedSafetyIndicators = safetyChecks.filter(c => c.regex.test(text)).map(c => c.key);

    return {
      captured: confirmedSafetyIndicators.length > 0,
      indicators: confirmedSafetyIndicators,
      sceneSafe: !confirmedSafetyIndicators.includes('hazard_on_road')
    };
  }

  /**
   * Inspects representative turns for prohibited coverage determinations or veterinary statements.
   */
  auditProhibitedStatements(turns = []) {
    const violations = [];

    // Filter to agent/representative turns if speaker labels exist, otherwise check all turns
    const candidateTurns = turns.length > 0
      ? turns.filter(t => !t.speaker || /^(?:agent|rep|representative|specialist|bot|intake|ai)/i.test(t.speaker))
      : [];

    for (const turn of candidateTurns) {
      const turnText = turn.text || '';
      for (const prohibited of PROHIBITED_COVERAGE_PATTERNS) {
        if (prohibited.pattern.test(turnText)) {
          const matchedExcerpt = turnText.match(prohibited.pattern)[0];
          violations.push({
            code: prohibited.code,
            severity: 'CRITICAL',
            description: prohibited.description,
            violatingExcerpt: matchedExcerpt,
            turnIndex: turn.index != null ? turn.index : null,
            speaker: turn.speaker || 'representative',
            statutoryBasis: 'Texas Insurance Code §4101 (Unauthorized Adjusting / Non-Adjudication Breach)'
          });
        }
      }
    }

    return violations;
  }
}

/**
 * AxiRate™ Call Review Agent
 * Orchestrates complete call review, confidence suppression, metric segregation,
 * and human appeal due process.
 */
class CallReviewAgent {
  constructor(options = {}) {
    this.confidenceThreshold = typeof options.confidenceThreshold === 'number'
      ? options.confidenceThreshold
      : DEFAULT_CONFIDENCE_THRESHOLD;

    this.appealManager = new DueProcessAppealManager();
    this.animalAuditor = new AnimalLossIntakeAuditor();
  }

  /**
   * Reviews a call transcript or structured call data object.
   * @param {string|Object} input - Raw text transcript or structured call object
   * @param {Object} reviewOptions - Optional per-call overrides
   * @returns {Object} Comprehensive AxiRate™ Call Review Report
   */
  reviewCall(input, reviewOptions = {}) {
    const callData = this.normalizeInput(input);
    const transcript = callData.transcript;
    const turns = callData.turns;

    const threshold = typeof reviewOptions.confidenceThreshold === 'number'
      ? reviewOptions.confidenceThreshold
      : this.confidenceThreshold;

    const reviewId = `REV-${Date.now()}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
    const timestamp = new Date().toISOString();

    // 1. Audio / Text Signal Quality & Confidence Degradation Factors
    const signalQuality = this.analyzeSignalQuality(transcript);

    // 2. Evaluate Metrics (Segregating Objective Process vs Conversational Inference)
    const metricResults = [];
    let objectiveProcessTotalWeight = 0;
    let objectiveProcessWeightedScore = 0;
    let objectiveProcessUnsuppressedWeight = 0;

    let conversationalInferenceTotalWeight = 0;
    let conversationalInferenceWeightedScore = 0;
    let conversationalInferenceUnsuppressedWeight = 0;

    for (const def of METRIC_DEFINITIONS) {
      const evaluation = this.evaluateMetric(def, transcript, turns, signalQuality, threshold);
      metricResults.push(evaluation);

      if (def.kind === METRIC_KINDS.OBJECTIVE_PROCESS) {
        objectiveProcessTotalWeight += def.weight;
        if (!evaluation.suppressed && evaluation.score !== null) {
          objectiveProcessWeightedScore += (evaluation.score * def.weight);
          objectiveProcessUnsuppressedWeight += def.weight;
        }
      } else if (def.kind === METRIC_KINDS.CONVERSATIONAL_INFERENCE) {
        conversationalInferenceTotalWeight += def.weight;
        if (!evaluation.suppressed && evaluation.score !== null) {
          conversationalInferenceWeightedScore += (evaluation.score * def.weight);
          conversationalInferenceUnsuppressedWeight += def.weight;
        }
      }
    }

    // 3. Sub-Category Scoring
    const objectiveProcessScore = objectiveProcessUnsuppressedWeight > 0
      ? Math.round(objectiveProcessWeightedScore / objectiveProcessUnsuppressedWeight)
      : null;

    const conversationalInferenceScore = conversationalInferenceUnsuppressedWeight > 0
      ? Math.round(conversationalInferenceWeightedScore / conversationalInferenceUnsuppressedWeight)
      : null;

    // 4. Animal Loss Nuance & Compliance Audit
    const animalLossAudit = this.animalAuditor.auditAnimalLoss(transcript, turns);

    // 5. Critical Violations Check
    const criticalViolations = [...animalLossAudit.complianceViolations];

    // If animal collision and bodily injury triage was omitted, flag violation
    if (animalLossAudit.isAnimalCollision && animalLossAudit.propertyDamageOnlyAssumptionError) {
      criticalViolations.push({
        code: 'OMITTED_ANIMAL_COLLISION_INJURY_TRIAGE',
        severity: 'HIGH',
        description: 'Intake treated animal collision as property damage only without inquiring whether any human occupants sustained bodily injuries.',
        statutoryBasis: 'Carrier Claims Intake Due Diligence & Bodily Injury Coverage Routing'
      });
    }

    // 6. Overall AxiRate Score & Confidence Determination
    const totalUnsuppressedWeight = objectiveProcessUnsuppressedWeight + conversationalInferenceUnsuppressedWeight;
    const totalPossibleWeight = objectiveProcessTotalWeight + conversationalInferenceTotalWeight;

    // Calculate mean confidence
    const meanConfidence = metricResults.reduce((acc, m) => acc + m.confidence, 0) / metricResults.length;
    const overallConfidence = parseFloat(meanConfidence.toFixed(2));

    let overallAxiRateScore = null;
    let scoreSuppressed = false;
    let suppressionReason = null;

    // Due-process rule: If overall confidence is below threshold, or >35% of weight suppressed, suppress composite score
    if (overallConfidence < threshold || (totalUnsuppressedWeight / totalPossibleWeight) < 0.65) {
      scoreSuppressed = true;
      suppressionReason = `Overall evaluation confidence (${overallConfidence.toFixed(2)}) is below the due-process reliability threshold (${threshold}). Automated score suppressed to protect against adverse employment and coverage denial errors.`;
      overallAxiRateScore = null;
    } else {
      // Calculate weighted score: 60% Objective Process / 40% Conversational Inference
      if (objectiveProcessScore !== null && conversationalInferenceScore !== null) {
        overallAxiRateScore = Math.round((objectiveProcessScore * 0.60) + (conversationalInferenceScore * 0.40));
      } else if (objectiveProcessScore !== null) {
        overallAxiRateScore = objectiveProcessScore;
      }

      // If critical violations exist, apply compliance cap
      if (criticalViolations.length > 0 && overallAxiRateScore !== null) {
        overallAxiRateScore = Math.min(overallAxiRateScore, 65);
      }
    }

    // 7. Human Re-Review Flagging
    let flagForHumanReview = scoreSuppressed || criticalViolations.length > 0;
    let humanReviewReason = null;

    if (criticalViolations.length > 0) {
      humanReviewReason = `Critical compliance violations detected (${criticalViolations.length} issue(s) flagged).`;
    } else if (scoreSuppressed) {
      humanReviewReason = suppressionReason;
    }

    // 8. Construct Complete Due-Process Report
    const report = {
      reviewId,
      callId: callData.callId || `CALL-${Date.now()}`,
      reviewedAt: timestamp,
      confidenceThreshold: threshold,
      overallConfidence,
      scoreSuppressed,
      suppressionReason,
      overallAxiRateScore,
      ratingBand: this.computeRatingBand(overallAxiRateScore, scoreSuppressed),

      // Metric Category Segregation
      categoryBreakdown: {
        objectiveProcess: {
          kind: METRIC_KINDS.OBJECTIVE_PROCESS,
          score: objectiveProcessScore,
          suppressed: objectiveProcessScore === null,
          description: 'Deterministic process metrics (verifiable disclosures, timestamps, preliminary notice).'
        },
        conversationalInference: {
          kind: METRIC_KINDS.CONVERSATIONAL_INFERENCE,
          score: conversationalInferenceScore,
          suppressed: conversationalInferenceScore === null,
          description: 'Subjective conversational inferences (empathy, tone, pacing). Non-determinative.'
        }
      },

      metricResults,
      animalLossAudit,
      criticalViolations,

      // Due-Process Appeal & Adverse Action Bar
      legalNotice: LEGAL_DUE_PROCESS_NOTICE.disclaimer,
      statutoryBasis: LEGAL_DUE_PROCESS_NOTICE.statutoryBasis,
      recordType: LEGAL_DUE_PROCESS_NOTICE.recordType,
      adverseActionGuards: {
        prohibitedFromAdverseEmployment: true,
        prohibitedFromClaimDenial: true,
        requiresHumanReviewForDiscipline: true,
        governingNotice: LEGAL_DUE_PROCESS_NOTICE.disclaimer
      },

      // Appeal State & Routing
      flagForHumanReview,
      humanReviewReason,
      appealStatus: APPEAL_STATUS.NONE,
      appealPending: false,
      humanReviewed: false,
      appealHistory: []
    };

    return report;
  }

  /**
   * Normalizes arbitrary input (string, JSON file path, object) into standard call format.
   */
  normalizeInput(input) {
    if (typeof input === 'string') {
      const trimmed = input.trim();
      // Check if file path
      if (fs.existsSync(input)) {
        const fileContent = fs.readFileSync(input, 'utf8');
        try {
          const parsed = JSON.parse(fileContent);
          return this.normalizeInput(parsed);
        } catch (_) {
          return this.normalizeInput(fileContent);
        }
      }
      // Check if raw JSON string
      if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
        try {
          const parsed = JSON.parse(trimmed);
          return this.normalizeInput(parsed);
        } catch (_) {
          // treat as plain text transcript
        }
      }
      return {
        transcript: trimmed,
        turns: this.parseTurnsFromText(trimmed)
      };
    } else if (typeof input === 'object' && input !== null) {
      const transcript = input.transcript || input.text || (Array.isArray(input.turns) ? input.turns.map(t => `${t.speaker || 'Speaker'}: ${t.text || ''}`).join('\n') : '');
      const turns = Array.isArray(input.turns) ? input.turns : this.parseTurnsFromText(transcript);
      return {
        callId: input.callId || input.id || null,
        transcript,
        turns
      };
    }
    throw new Error('Unsupported call input format. Provide string transcript or call object.');
  }

  /**
   * Heuristic speaker turn parser for plain-text transcripts.
   */
  parseTurnsFromText(text) {
    const lines = text.split(/\r?\n/).map(l => l.trim()).filter(Boolean);
    const turns = [];
    const speakerRegex = /^([a-zA-Z0-9_\s]{2,20})\s*:\s*(.+)$/;

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const match = line.match(speakerRegex);
      if (match) {
        turns.push({
          index: i,
          speaker: match[1].trim(),
          text: match[2].trim()
        });
      } else {
        turns.push({
          index: i,
          speaker: 'Speaker',
          text: line
        });
      }
    }
    return turns;
  }

  /**
   * Analyzes audio/transcript quality signals to determine baseline confidence.
   */
  analyzeSignalQuality(transcript) {
    const wordCount = transcript.split(/\s+/).filter(Boolean).length;
    const inaudibleMatches = transcript.match(/\[(?:inaudible|muffled|static|unclear|crosstalk|garbled)\]/gi) || [];
    const inaudibleCount = inaudibleMatches.length;

    let degradationPenalty = 0;
    if (wordCount < 40) {
      degradationPenalty += 0.25; // extremely short or incomplete call
    } else if (wordCount < 80) {
      degradationPenalty += 0.10;
    }

    if (inaudibleCount > 0) {
      degradationPenalty += Math.min(0.40, inaudibleCount * 0.10);
    }

    const audioSignalFactor = Math.max(0.20, parseFloat((1.0 - degradationPenalty).toFixed(2)));

    return {
      wordCount,
      inaudibleCount,
      audioSignalFactor,
      isDegraded: degradationPenalty > 0.15
    };
  }

  /**
   * Evaluates an individual metric with confidence scoring and suppression logic.
   */
  evaluateMetric(def, transcript, turns, signalQuality, threshold) {
    let rawScore = 0;
    let confidence = def.baseConfidence * signalQuality.audioSignalFactor;
    let passed = false;
    let evidence = null;

    const isTradeCall = /\b(plumbing|hvac|roofing|electrical|dental|legal|personal\s+injury|dispatch\s+specialist|especialista\s+de\s+(?:despacho\s+de\s+)?plomer[íi]a|Agent\s+Angel\s+Plumbing|service\s+(?:order|request)|technician|t[ée]cnico|tarping|breaker|molar|18-wheeler)\b/i.test(transcript);

    if (def.kind === METRIC_KINDS.OBJECTIVE_PROCESS) {
      // Deterministic keyword matching (evaluates caller utterances when def.callerOnly is true)
      const callerTurns = Array.isArray(turns)
        ? turns.filter(t => /^(caller|customer|user|insured|claimant)/i.test(String(t.speaker || '')))
        : [];
      const targetText = (def.callerOnly && callerTurns.length > 0)
        ? callerTurns.map(t => t.text).join('\n')
        : transcript;
      let effectiveKeywords = def.requiredKeywords;
      if (isTradeCall && def.id === 'OP_POLICY_IDENTIFIER') {
        effectiveKeywords = [/\b(?:address|street|drive|avenue|road|lane|blvd|boulevard|burst|leak|pipe|water\s+heater|ac\s+unit|shingles|breaker|molar|18-wheeler|emergency|priority\s+dispatch)\b/i];
      } else if (isTradeCall && def.id === 'OP_PRELIMINARY_INTAKE_DISCLAIMER') {
        effectiveKeywords = [/\b(?:confirm|on-call\s+technician|service\s+request|ticket\s+reference|dispatch|t[ée]cnico|attorney)\b/i];
      } else if (isTradeCall && def.id === 'OP_INCIDENT_DATETIME') {
        effectiveKeywords = [/\b(?:today|tomorrow|right\s+away|as\s+soon\s+as\s+possible|within\s+the\s+next\s+hour|morning|afternoon|between\s+\d|\d{1,2}\s*(?:am|pm)|emergency|hoy|lo\s+antes\s+posible)\b/i];
      }
      let matches = 0;
      for (const kw of effectiveKeywords) {
        if (kw.test(targetText)) {
          matches++;
          if (!evidence) evidence = targetText.match(kw)[0];
        }
      }
      if (def.disqualifyTranscriptPattern && def.disqualifyTranscriptPattern.test(transcript)) {
        matches = 0;
        evidence = null;
      }
      const matchRatio = effectiveKeywords.length > 0 ? (matches / effectiveKeywords.length) : 0;
      rawScore = Math.round(matchRatio * 100);
      passed = rawScore >= 70;

      // Objective process with high keyword match has high confidence
      if (matchRatio >= 1.0) {
        confidence = Math.min(0.99, confidence + 0.05);
      }
    } else if (def.kind === METRIC_KINDS.CONVERSATIONAL_INFERENCE) {
      // Conversational inference evaluation
      let positiveCount = 0;
      let negativeCount = 0;

      if (Array.isArray(def.positiveKeywords)) {
        for (const kw of def.positiveKeywords) {
          if (kw.test(transcript)) {
            positiveCount++;
            if (!evidence) evidence = transcript.match(kw)[0];
          }
        }
      }

      if (Array.isArray(def.negativeKeywords)) {
        for (const kw of def.negativeKeywords) {
          if (kw.test(transcript)) {
            negativeCount++;
          }
        }
      }

      if (Array.isArray(def.jargonPatterns)) {
        for (const kw of def.jargonPatterns) {
          if (kw.test(transcript)) {
            negativeCount += 2;
          }
        }
      }

      // Base conversational score
      let scoreCalc = 80 + (positiveCount * 10) - (negativeCount * 25);
      rawScore = Math.max(0, Math.min(100, scoreCalc));
      passed = rawScore >= 70;

      // Conversational inferences inherently carry wider confidence bounds
      confidence = Math.min(0.90, confidence * 0.95);
    }

    confidence = parseFloat(confidence.toFixed(2));
    const isSuppressed = confidence < threshold;

    return {
      id: def.id,
      name: def.name,
      kind: def.kind,
      weight: def.weight,
      confidence,
      suppressed: isSuppressed,
      suppressionReason: isSuppressed
        ? `Confidence (${confidence.toFixed(2)}) is below due-process reliability threshold (${threshold}). Automated score withheld.`
        : null,
      score: isSuppressed ? null : rawScore,
      passed: isSuppressed ? null : passed,
      evidence: isSuppressed ? null : evidence,
      requiresHumanReview: isSuppressed
    };
  }

  /**
   * Maps numerical score to institutional rating band.
   */
  computeRatingBand(score, isSuppressed) {
    if (isSuppressed || score === null) return 'SUPPRESSED_PENDING_REVIEW';
    if (score >= 90) return 'EXCELLENT_COMPLIANT';
    if (score >= 80) return 'PROFICIENT';
    if (score >= 70) return 'COACHING_RECOMMENDED';
    return 'SUB_STANDARD_REVIEW_REQUIRED';
  }

  /**
   * Validates whether a proposed organizational action is permissible under due process law.
   * Explicitly bars AI-only scores from adverse employment actions or claim denials.
   */
  assertActionLegality(report, proposedAction) {
    const action = String(proposedAction || '').toUpperCase();
    const isProhibited = LEGAL_DUE_PROCESS_NOTICE.adverseActionProhibitions.includes(action);

    if (isProhibited) {
      if (!report.humanReviewed) {
        return {
          permitted: false,
          violation: 'PROHIBITED_AI_ONLY_ADVERSE_ACTION',
          reason: `Proposed action '${action}' violates due process law. Automated AxiRate™ scores cannot serve as the sole or determinative basis for adverse employment discipline or claim denial without human supervisor adjudication.`,
          statutoryBasis: LEGAL_DUE_PROCESS_NOTICE.statutoryBasis,
          requiredRemedy: 'Submit call report to human supervisor review queue prior to taking adverse personnel or claims actions.'
        };
      }
      if (report.appealPending) {
        return {
          permitted: false,
          violation: 'ACTION_BLOCKED_PENDING_APPEAL',
          reason: `Proposed action '${action}' is stayed pending resolution of active due-process appeal (${report.appealStatus}).`,
          requiredRemedy: 'Resolve outstanding employee/agent appeal before taking formal action.'
        };
      }
    }

    return {
      permitted: true,
      action,
      humanReviewed: report.humanReviewed,
      appealStatus: report.appealStatus
    };
  }
}

/**
 * Recomputes report composite scores after human appeal modification.
 */
function recomputeReportScores(report) {
  let objWeight = 0;
  let objScoreSum = 0;
  let ciWeight = 0;
  let ciScoreSum = 0;

  for (const m of report.metricResults) {
    if (!m.suppressed && typeof m.score === 'number') {
      if (m.kind === METRIC_KINDS.OBJECTIVE_PROCESS) {
        objWeight += m.weight;
        objScoreSum += (m.score * m.weight);
      } else if (m.kind === METRIC_KINDS.CONVERSATIONAL_INFERENCE) {
        ciWeight += m.weight;
        ciScoreSum += (m.score * m.weight);
      }
    }
  }

  const objScore = objWeight > 0 ? Math.round(objScoreSum / objWeight) : null;
  const ciScore = ciWeight > 0 ? Math.round(ciScoreSum / ciWeight) : null;

  report.categoryBreakdown.objectiveProcess.score = objScore;
  report.categoryBreakdown.conversationalInference.score = ciScore;

  if (objScore !== null && ciScore !== null) {
    report.overallAxiRateScore = Math.round((objScore * 0.60) + (ciScore * 0.40));
  } else if (objScore !== null) {
    report.overallAxiRateScore = objScore;
  }
}

